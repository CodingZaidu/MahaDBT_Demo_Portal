export function setLocale(locale) {
  currentLocale = LANGUAGES.includes(locale) ? locale : "en";
  if (typeof document !== "undefined") document.documentElement.lang = currentLocale;
}

export function getLocale() {
  return currentLocale;
}

const LANGUAGES = ["en", "hi", "mr"];

export function t(value) {
  if (typeof value !== "string" || currentLocale === "en") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const key = value.trim();
  if (!key) return value;
  const dictionary = phraseTranslations[currentLocale] || {};
  const wordMap = wordTranslations[currentLocale] || {};
  const translated = dictionary[key] || wordMap[key] || key;
  return `${leading}${translated}${trailing}`;
}
